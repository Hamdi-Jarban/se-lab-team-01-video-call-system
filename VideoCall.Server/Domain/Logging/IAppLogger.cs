namespace VideoCall.Server.Domain.Logging;

/// <summary>
/// عقد موحد لخدمات تسجيل الأحداث والأخطاء الخاصة بالخادم.
///
/// يحدد هذا العقد العمليات الأساسية التي تحتاجها طبقات التطبيق والبنية
/// التحتية لتسجيل المعلومات والتحذيرات والأخطاء، دون ربطها بطريقة التسجيل
/// الفعلية أو بمكان تخزين السجلات.
///
/// يعتمد التصميم على مبدأ عكس اتجاه الاعتماد
/// (Dependency Inversion Principle)، بحيث تعتمد الطبقات العليا على هذه
/// الواجهة، بينما يتم وضع تفاصيل التنفيذ داخل طبقة Infrastructure.
///
/// في التنفيذ الحالي تستخدم الخدمة ConsoleAppLogger لإظهار السجلات في
/// نافذة Console، ولكن يمكن استبدالها لاحقًا بتنفيذ آخر دون تعديل الكلاسات
/// التي تعتمد على IAppLogger، مثل:
/// - خدمة تسجيل مركزية.
/// - ملف محلي أو قاعدة بيانات.
/// - منصة مراقبة وتنبيهات.
/// - تنفيذ وهمي Fake Logger لاختبارات الوحدة.
///
/// استخدام واجهة بدل Logger من النوع static يحقق الفوائد التالية:
/// - تقليل الاعتماديات الخفية داخل الكلاسات.
/// - تسهيل كتابة اختبارات الوحدة.
/// - إمكانية اعتراض السجلات والتحقق منها أثناء الاختبار.
/// - فصل منطق التطبيق عن تفاصيل الإخراج والتخزين.
/// - توحيد أسلوب التسجيل في جميع أجزاء الخادم.
/// </summary>
public interface IAppLogger
{
    /// <summary>
    /// يسجل معلومة مرتبطة بحدث تشغيلي طبيعي داخل النظام.
    /// </summary>
    /// <param name="message">
    /// نص المعلومة المراد تسجيلها.
    /// </param>
    void Info(string message);

    /// <summary>
    /// يسجل تحذيرًا يشير إلى سلوك غير متوقع أو حالة تحتاج إلى متابعة،
    /// دون أن يعني ذلك بالضرورة توقف الخدمة.
    /// </summary>
    /// <param name="message">
    /// نص التحذير المراد تسجيله.
    /// </param>
    void Warn(string message);

    /// <summary>
    /// يسجل خطأ حدث أثناء تنفيذ عملية داخل الخادم.
    /// يستخدم هذا المستوى للحالات التي قد تؤثر على الاتصال أو الوظيفة
    /// الحالية وتحتاج إلى تحليل من فريق التطوير أو التشغيل.
    /// </summary>
    /// <param name="message">
    /// تفاصيل الخطأ المراد تسجيلها.
    /// </param>
    void Error(string message);
}
