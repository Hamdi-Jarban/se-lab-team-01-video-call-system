using VideoCall.Shared.Messages;

namespace VideoCall.Server.Domain;

/// <summary>
/// يمثل هذا العقد جلسة الاتصال بين الخادم وعميل واحد.
///
/// يوفّر IClientHandler طبقة تجريد بين منطق التطبيق ووسيلة الاتصال الفعلية.
/// لذلك لا تحتاج طبقات Application وDomain إلى معرفة ما إذا كان الاتصال
/// يستخدم TCP أو أي وسيلة نقل أخرى.
///
/// تعتمد طبقة التطبيق على هذا العقد لتنفيذ العمليات الأساسية التالية:
/// - معرفة هوية الجلسة والمستخدم المرتبط بها.
/// - التحقق من حالة المصادقة.
/// - إرسال الرسائل إلى العميل.
/// - إغلاق الاتصال بطريقة آمنة ومنظمة.
///
/// يتم تنفيذ هذا العقد حاليًا بواسطة ClientSession الموجودة في طبقة
/// Infrastructure.Networking، ويمكن استخدام تنفيذ بديل داخل الاختبارات،
/// مثل InMemoryClientHandler، دون تعديل منطق التطبيق.
///
/// يحقق هذا التصميم المبادئ التالية:
/// - مبدأ التجريد (Abstraction).
/// - مبدأ عكس اتجاه الاعتماد (Dependency Inversion Principle).
/// - مبدأ استبدال ليسكوف (Liskov Substitution Principle).
/// </summary>
public interface IClientHandler
{
    /// <summary>
    /// رمز فريد يتم إنشاؤه للجلسة ويُرسل للعميل بعد نجاح تسجيل الدخول.
    ///
    /// يستخدم هذا الرمز أيضًا للتحقق من ملكية حزم الوسائط القادمة عبر UDP،
    /// ولذلك يجب التعامل معه على أنه قيمة حساسة وعدم تسجيله في السجلات
    /// العامة أو عرضه للمستخدم النهائي.
    /// </summary>
    Guid SessionToken { get; }

    /// <summary>
    /// اسم المستخدم الذي تمت مصادقته وربطه بهذه الجلسة.
    ///
    /// تكون القيمة null قبل اكتمال تسجيل الدخول بنجاح.
    /// </summary>
    string? Username { get; }

    /// <summary>
    /// يحدد ما إذا كانت الجلسة قد اجتازت مرحلة المصادقة.
    ///
    /// تستخدم ProtocolRouter هذه الخاصية لمنع تنفيذ عمليات المكالمات
    /// أو الغرف قبل تسجيل الدخول.
    /// </summary>
    bool IsAuthenticated { get; }

    /// <summary>
    /// يربط الجلسة بالمستخدم بعد نجاح التحقق من بيانات تسجيل الدخول.
    ///
    /// يجب استدعاء هذه الدالة بعد نجاح ICredentialValidator وبعد تسجيل
    /// المستخدم في IUserPresenceRepository.
    /// </summary>
    /// <param name="username">
    /// اسم المستخدم الذي تمت مصادقته.
    /// </param>
    void SetAuthenticatedUsername(string username);

    /// <summary>
    /// يرسل رسالة إلى العميل عبر قناة الاتصال الحالية.
    ///
    /// تستخدم هذه الدالة لإرسال LoginResponse ونتائج العمليات الأخرى.
    /// يجب انتظار المهمة الناتجة عنها لضمان اكتمال الإرسال ومعالجة أخطاء
    /// الشبكة، بدل استخدام fire-and-forget غير المراقب.
    /// </summary>
    /// <param name="message">
    /// الرسالة التي سيتم إرسالها.
    /// </param>
    /// <param name="ct">
    /// رمز الإلغاء المرتبط بدورة حياة الطلب أو الخادم.
    /// </param>
    /// <returns>
    /// مهمة تكتمل بعد إرسال الرسالة أو تفشل عند تعذر الإرسال.
    /// </returns>
    Task SendAsync(
        Message message,
        CancellationToken ct = default);

    /// <summary>
    /// يغلق جلسة العميل بطريقة منظمة وقابلة للتكرار بأمان.
    ///
    /// يجب أن تكون العملية Idempotent؛ أي إن استدعاءها أكثر من مرة
    /// لا يؤدي إلى تنفيذ التنظيف أو إشعار registry أكثر من مرة.
    ///
    /// عند الإغلاق يتم عادةً:
    /// - إلغاء حلقة قراءة الرسائل.
    /// - تحرير موارد الاتصال.
    /// - إشعار IClientSessionRegistry بانتهاء الجلسة.
    /// - تنفيذ تنظيف الحضور والمحادثات المرتبطة بالمستخدم.
    /// </summary>
    /// <returns>
    /// مهمة تكتمل بعد إغلاق الجلسة وتنفيذ إشعار الإغلاق.
    /// </returns>
    Task CloseAsync();
}
