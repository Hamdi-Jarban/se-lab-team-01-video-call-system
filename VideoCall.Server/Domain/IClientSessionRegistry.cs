namespace VideoCall.Server.Domain;

/// <summary>
/// عقد سجل جلسات العملاء المفتوحة داخل الخادم.
///
/// يتم إشعار هذا السجل بعد إغلاق جلسة العميل بالكامل، حتى يتمكن المكوّن
/// المسؤول عن إدارة الاتصالات من تنفيذ الإجراءات اللاحقة، مثل:
/// - إزالة الجلسة من قائمة الاتصالات النشطة.
/// - إزالة المستخدم من Presence Repository.
/// - تنظيف المحادثات والغرف المرتبطة به.
/// - إزالة نقاط UDP الخاصة به عند الحاجة.
/// - بث تحديث حالة الاتصال إلى بقية العملاء.
///
/// لا يهتم هذا العقد بتفاصيل تنفيذ الاتصال أو نوع الناقل المستخدم. فهو
/// يعتمد على IClientHandler فقط، مما يحافظ على الفصل بين طبقة النقل وطبقات
/// التطبيق والمجال.
///
/// يتم تنفيذ هذا العقد حاليًا بواسطة ServerHost، لأنه المسؤول عن:
/// - قبول اتصالات TCP الجديدة.
/// - تتبع جميع جلسات العملاء الحالية.
/// - تنسيق عمليات الإغلاق والتنظيف.
///
/// يساعد هذا التصميم على تطبيق مبدأ عكس اتجاه الاعتماد
/// (Dependency Inversion Principle)، كما يسمح باستخدام تنفيذ بديل أثناء
/// اختبارات الوحدة دون الحاجة إلى تشغيل TCP Listener فعلي.
/// </summary>
public interface IClientSessionRegistry
{
    /// <summary>
    /// يتم استدعاؤها بعد اكتمال إغلاق جلسة العميل.
    ///
    /// يجب أن تكون عملية التنظيف آمنة عند استدعائها أكثر من مرة، بحيث لا
    /// يؤدي تكرار الإشعار إلى حذف بيانات جلسة جديدة أو تنفيذ التنظيف مرتين.
    ///
    /// يستقبل المكوّن المسجل جلسة العميل حتى يستطيع مطابقة الجلسة الفعلية
    /// مع السجل الحالي قبل إزالتها، خصوصًا عند إعادة اتصال المستخدم بسرعة.
    /// </summary>
    /// <param name="session">
    /// جلسة العميل التي انتهت دورة حياتها.
    /// </param>
    /// <returns>
    /// مهمة تكتمل بعد انتهاء إزالة الجلسة وتنفيذ عمليات التنظيف المرتبطة بها.
    /// </returns>
    Task OnSessionClosedAsync(IClientHandler session);
}
